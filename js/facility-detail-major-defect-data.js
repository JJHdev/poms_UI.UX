  function normalizeActionStages(stages) {
    return (stages || DEFAULT_ACTION_STAGES).map((stage) => {
      if (stage.deadlineDate !== undefined) {
        return { ...stage };
      }
      const legacyDeadline = String(stage.deadline || '');
      const legacyDate = String(stage.date || '');
      const deadlineMatch = legacyDeadline.match(/^(\d{4}-\d{2}-\d{2})/);
      const dateMatch = legacyDate.match(/^(\d{4}-\d{2}-\d{2})/);
      return {
        stage: stage.stage,
        deadlineDate: deadlineMatch ? deadlineMatch[1] : '',
        deadlineNote: deadlineMatch ? legacyDeadline.slice(deadlineMatch[0].length).trim() : legacyDeadline,
        actionDate: dateMatch ? dateMatch[1] : '',
        dateNote: dateMatch ? legacyDate.slice(dateMatch[0].length).trim() : legacyDate,
        content: stage.content || '',
      };
    });
  }

